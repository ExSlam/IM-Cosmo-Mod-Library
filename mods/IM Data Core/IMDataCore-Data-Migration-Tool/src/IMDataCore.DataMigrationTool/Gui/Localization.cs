    public static IReadOnlyList<LanguageOption> Languages { get; } =
        new[]
        {
            new LanguageOption("en", "English"),
            new LanguageOption("pt-BR", "Português (Brasil)"),
            new LanguageOption("ru", "Русский"),
            new LanguageOption("fr", "Français"),
            new LanguageOption("ja", "日本語"),
            new LanguageOption("ko", "한국어"),
            new LanguageOption("zh-Hans", "简体中文")
        };

    public static string CurrentCode { get; private set; } = "en";

    public static event Action? LanguageChanged;

    public static string InitializeFromSystemCulture()
    {
        string resolved = "en";
        try
        {
            CultureInfo culture = CultureInfo.CurrentUICulture;
            string name = culture.Name ?? string.Empty;
            string language = culture.TwoLetterISOLanguageName.ToLowerInvariant();

            resolved = language switch
            {
                "en" => "en",
                "fr" => "fr",
                "ru" => "ru",
                "ja" => "ja",
                "ko" => "ko",
                "pt" when name.Equals("pt-BR", StringComparison.OrdinalIgnoreCase) || name.Length == 0 => "pt-BR",
                "zh" when name.StartsWith("zh-CN", StringComparison.OrdinalIgnoreCase)
                          || name.StartsWith("zh-SG", StringComparison.OrdinalIgnoreCase)
                          || name.Contains("Hans", StringComparison.OrdinalIgnoreCase) => "zh-Hans",
                _ => "en"
            };
        }
        catch
        {
            resolved = "en";
        }

        SetLanguage(resolved);
        return CurrentCode;
    }

    public static string T(string key)
    {
        if (_strings.TryGetValue(CurrentCode, out Dictionary<string, string>? current) && current.TryGetValue(key, out string? value))
            return value;
        if (_strings.TryGetValue("en", out Dictionary<string, string>? english) && english.TryGetValue(key, out value))
            return value;
        return key;
    }

    public static string Format(string key, params object[] args) => string.Format(CultureInfo.CurrentCulture, T(key), args);

    public static void SetLanguage(string code)
    {
        if (string.IsNullOrWhiteSpace(code)) code = "en";
        if (!_strings.ContainsKey(code)) code = "en";
        if (string.Equals(CurrentCode, code, StringComparison.OrdinalIgnoreCase)) return;
        CurrentCode = code;
        LanguageChanged?.Invoke();
    }
